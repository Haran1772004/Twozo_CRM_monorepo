package com.tlc.crm.workflow.api.model;

/**
 * A model that represents the {@link FieldGroup}.
 *
 * @author ThalaimalaiPandiyanT
 * @version 1.0
 */
public enum FieldGroup {

    /**
     * Indicates the field is source related fields.
     */
    SOURCE_RELATED_FIELD,

    /**
     * Indicates the field is associated only for workflow.
     */
    WORKFLOW_RELATED_FIELD;
}
