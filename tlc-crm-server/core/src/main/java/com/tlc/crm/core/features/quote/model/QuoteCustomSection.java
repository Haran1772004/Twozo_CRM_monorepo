package com.tlc.crm.core.features.quote.model;

import com.tlc.commons.template.model.Section;
import com.tlc.commons.util.StringUtil;

import java.util.Objects;

/**
 * Represents a custom section in a quotation template.
 *
 * <p>This record defines dynamically added quotation sections that are not part
 * of the predefined {@link QuoteSection} values. Each custom section contains
 * a unique identifier and a display name.
 *
 * <p>The section ID is formatted to match the HTML element ID convention used
 * during template processing.
 *
 * @author Sathish
 * @version 1.0
 */
public record QuoteCustomSection(String id, String name) implements Section {

    private static final String SECTION = "section";

    /**
     * Returns the formatted HTML element identifier for this custom section.
     *
     * <p>The returned ID is generated by prefixing the custom section identifier
     * with the section prefix used in quotation templates.
     *
     * @return Formatted HTML section identifier.
     */
    @Override
    public String id() {
        return StringUtil.join(StringUtil.Delimiter.HYPHEN, SECTION, id);
    }

    /**
     * Compares this custom section with another object for equality.
     *
     * <p>Custom sections are considered equal when their identifiers are equal.
     * The section name is not considered during equality comparison.
     *
     * @param object Object to compare with this custom section.
     * @return {@code true} if both objects represent the same section identifier,
     *         otherwise {@code false}.
     */
    @Override
    public boolean equals(final Object object) {
        if (object == null || getClass() != object.getClass()) {
            return false;
        }
        final QuoteCustomSection that = (QuoteCustomSection) object;

        return Objects.equals(id, that.id);
    }

    /**
     * Returns the hash code for this custom section.
     *
     * <p>The hash code is generated using only the section identifier to maintain
     * consistency with the {@link #equals(Object)} implementation.
     *
     * @return Hash code value based on the section identifier.
     */
    @Override
    public int hashCode() {
        return Objects.hashCode(id);
    }
}