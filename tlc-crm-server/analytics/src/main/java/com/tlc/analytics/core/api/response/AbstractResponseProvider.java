package com.tlc.analytics.core.api.response;

import com.tlc.analytics.config.model.view.ViewDetails;
import com.tlc.analytics.config.model.view.ViewModel;
import com.tlc.analytics.core.api.ViewRequest;
import com.tlc.analytics.core.api.ViewResponse;
import com.tlc.analytics.core.api.cache.AnalyticsCacheService;
import com.tlc.analytics.core.api.creator.ViewResponseCreator;
import com.tlc.analytics.core.api.GraphAxis;
import com.tlc.commons.json.JsonObject;

import com.tlc.commons.util.executor.NullSafeExecutor;
import lombok.NonNull;

import javax.annotation.Nullable;
import java.util.List;
import java.util.Optional;

/**
 * Abstract base class implementing the {@link ResponseProvider} interface for generating responses to view requests.
 *
 * @param <V> The type of view.
 * @param <Request> The type of view request handled by this response provider.
 * @param <Response> The type of view response generated by this response provider.
 *
 * @author Aswath
 * @version 1.0
 */
public abstract class AbstractResponseProvider<V extends ViewModel, Request extends ViewRequest<V>, Response extends ViewResponse<Request>>
        implements ResponseProvider<V, Request>
{
    /**
     * Retrieves the response JSON object for the given view request.
     * This method first attempts to fetch the response from cache,
     * and if not found or outdated, generates the response from the database.
     *
     * @param request The view request for which to retrieve the response. Must not be null.
     * @return The response JSON object.
     * @throws Exception if an error occurs while generating the response.
     */
    @Override
    public @NonNull JsonObject getJsonResponse( final @NonNull Request request ) throws Exception
    {
        final String cacheKey = generateCacheKey( request );
        final JsonObject cachedData = getRespFromCache( request, cacheKey );

        return NullSafeExecutor.orElseGetSafely( cachedData, () -> {

                   final Response viewResponse = getRespFromDB( request );
                   final JsonObject resp = generateResponse(viewResponse, request );
                   AnalyticsCacheService.getInstance().store( cacheKey, resp );
                   return resp;
               } );
    }

    @Override
    public @NonNull List<GraphAxis<Object>> getGraphAxisResponse( final @NonNull Request request ) throws Exception
    {
        // TODO: Need To handle Cache for this.
        final Response viewResponse = getRespFromDB( request );
        return generateGraphAxis(viewResponse, request );
    }



    /**
     * Retrieves the view response from the database for the given view request.
     *
     * @param request The view request for which to fetch the response. Must not be null.
     * @return The generated view response.
     * @throws Exception if an error occurs while fetching the response.
     */
    protected @NonNull Response getRespFromDB(final Request request) throws Exception
    {
        return getResponseCreator().create(request);
    }

    /**
     * Retrieves the response JSON object from the cache for the given view request.
     *
     * @param request      The view request for which to retrieve the cached response. Must not be null.
     * @param cacheKey The cache key associated with the response. Must not be null.
     * @return The cached response JSON object, or null if not found or outdated.
     */
    protected @Nullable JsonObject getRespFromCache(final Request request, final String cacheKey )
    {
        return Optional.ofNullable( AnalyticsCacheService.getInstance().getCache( cacheKey ) )
                       .stream()
                       .filter( cache -> {

                           final long cacheGenTime = cache.optLong( "CACHE_GEN_TIME", -1L );

                           if( isModified(request, cacheGenTime ) )
                           {
                               AnalyticsCacheService.getInstance().remove( cacheKey );
                               return false;
                           }
                           else
                           {
                               return true;
                           }
                       } ).findFirst().orElse( null );
    }

    /**
     * Checks if the cached response is outdated based on the modification time of the view and its columns.
     *
     * @param request          The view request for which the response is being checked.
     * @param cacheGenTime The timestamp when the cached response was generated.
     * @return True if the cached response is outdated, otherwise false.
     */
    private boolean isModified( final Request request, final Long cacheGenTime )
    {
        final V view = request.getView();
        final ViewDetails viewDetails = view.getViewDetails();
        final Long modTime = viewDetails.getModifiedTime();
        if( cacheGenTime < modTime )
        {
            return true;
        }
        return isViewModified(request, cacheGenTime );
    }

    /**
     * Subclasses can override this method to implement their own logic for checking if the view
     * or its related data has been modified since the cached response was generated.
     *
     * @param request          The view request for which the response is being checked.
     * @param cacheGenTime The timestamp when the cached response was generated.
     * @return True if the cached response is outdated, otherwise false.
     */
    protected boolean isViewModified(final Request request, final Long cacheGenTime )
    {
        return false;
    }

    /**
     * Retrieves the view response creator implementation.
     *
     * @return The view response creator. Must not be null.
     */
    @NonNull
    abstract protected ViewResponseCreator<V, Request, Response> getResponseCreator();

    /**
     * Generates the response JSON object from the view response.
     *
     * @param response The view response to generate the JSON object from. Must not be null.
     * @param request  The view request for which to generate the cache key.
     * @return The generated response JSON object. Must not be null.
     */
    @NonNull
    abstract protected JsonObject generateResponse( final Response response, final Request request );

    /**
     * Generates a list of GraphAxis objects based on the given response and request
     *
     * @param response The view response to generate the JSON object from.
     * @param request  The view request for which to generate the cache key.
     * @return List of {@link GraphAxis} objects representing the generated axes for the graph
     */
    abstract protected @NonNull List<GraphAxis<Object>> generateGraphAxis( final Response response, final Request request );

    /**
     * Generates the cache key for the given view request.
     *
     * @param request The view request for which to generate the cache key. Must not be null.
     * @return The generated cache key. Must not be null.
     */
    @NonNull
    abstract protected String generateCacheKey( final @NonNull Request request);
}
