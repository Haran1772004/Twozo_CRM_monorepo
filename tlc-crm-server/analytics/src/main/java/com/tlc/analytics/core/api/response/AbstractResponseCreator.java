/**
 * <p>
 * Abstract base class implementing the {@link ViewResponseCreator} interface for generating
 * responses to view requests. Handles data fetching, graph axis construction, and response generation.
 * </p>
 *
 * @param <V>        The type of view.
 * @param <Request>  The type of view request handled by this response creator.
 * @param <Response> The type of view response generated by this response creator.
 * @author Jamesh
 * @version 1.0
 */
public abstract class AbstractResponseCreator<V extends AnalyticsReport, Request extends DataViewRequest<V>, Response extends ViewResponse<Request>>
        implements ViewResponseCreator<V, Request, Response> {
    private static final String CTE_ALIAS = "filtered_data";
    private static final Pattern COLUMN_SUFFIX_PATTERN = Pattern.compile(".*_(\\d+)$");
    private static final Logger LOGGER = LoggerFactory.getLogger(AbstractResponseCreator.class);

    private final AnalyticsDataFetcher analyticsDataFetcher;

    /**
     * Creates response creator dependencies.
     */
    protected AbstractResponseCreator() {
        this.analyticsDataFetcher = AnalyticsDataFetcher.getInstance();
    }

    /**
     * {@inheritDoc}
     *
     * @param request The view request for which to create the response. Must not be null.
     * @return the generated response object.
     * @throws Exception If any error occurs during response creation
     */
    @Override
    public final @NonNull Response create(final @NonNull Request request) throws Exception {
        final With with = getSelectQueryConverter().convert(request);
        final V view = request.getView();
        final boolean isApplyConfiguration = request.isApplyConfiguration();
        final OperationType operationType = request.getOperationType();
        final Long orgId = request.getOrgId();
        final AnalyticsLimit analyticsLimit = buildAnalyticsLimit(request);
        final SelectQuery selectQuery = with.getDerivedTables().stream().filter(table -> CTE_ALIAS.equalsIgnoreCase(table.getAlias()))
                .findFirst().orElse(null).getSelectQuery();
        final Long totalRecords = getTotalRecords(orgId, selectQuery);
        final List<GraphAxis<Object>> xAxisList = new ArrayList<>();
        final List<GraphAxis<Object>> yAxisList = new ArrayList<>();
        final List<GraphAxis<Object>> underlyingDataList = new ArrayList<>();

        if (with.getSelectQuery() instanceof final OlapSelectQuery olapOuterQuery) {
            olapOuterQuery.returnUpdatedData(true);
        }

        if (NumericalConstant.ZERO < totalRecords) {
            final RowProcessingContext context = buildRowProcessingContext(view, isApplyConfiguration, request);

            processDataRows(orgId, with, isApplyConfiguration, operationType,
                    totalRecords, analyticsLimit, context, xAxisList, yAxisList, underlyingDataList);
        } else {
            generateNoDataResponse(totalRecords, xAxisList, yAxisList, view, operationType, analyticsLimit);
        }

        if (xAxisList.isEmpty() && yAxisList.isEmpty() && underlyingDataList.isEmpty()) {
            generateNoDataResponse(totalRecords, xAxisList, yAxisList, view, operationType, analyticsLimit);
            LOGGER.warn("Analytics: No data found for the given query and parameters, orgId [{}]", orgId);
        }

        LOGGER.info("Analytics: Graph axis object successfully constructed, orgId [{}]", orgId);

        return getResponse(buildFinalGraphAxes(request, xAxisList, yAxisList, underlyingDataList));
    }

    /**
     * <p>
     * Builds the {@link AnalyticsLimit} from the request start/limit values, applying defaults when null.
     * </p>
     *
     * @param request the view request
     * @return the constructed analytics limit
     */
    private AnalyticsLimit buildAnalyticsLimit(final Request request) {
        final Integer start = request.getStart();
        final Integer limit = request.getLimit();

        return new AnalyticsLimit(start != null ? start : NumericalConstant.ONE, limit != null ? limit : NumericalConstant.TEN);
    }

    /**
     * <p>
     * Builds the final combined list of graph axes based on request type (underlying vs chart).
     * </p>
     *
     * @param request            the view request
     * @param xAxisList          x-axis graph axes
     * @param yAxisList          y-axis graph axes
     * @param underlyingDataList underlying data graph axes
     * @return combined graph axes list for the response
     */
    private List<GraphAxis<Object>> buildFinalGraphAxes(final Request request,
                                                        final List<GraphAxis<Object>> xAxisList,
                                                        final List<GraphAxis<Object>> yAxisList,
                                                        final List<GraphAxis<Object>> underlyingDataList) {
        final List<GraphAxis<Object>> graphAxes = new ArrayList<>();

        if (request.isUnderlyingRequest()) {
            graphAxes.addAll(underlyingDataList);
        } else {
            graphAxes.addAll(xAxisList);
            graphAxes.addAll(yAxisList);
        }

        return graphAxes;
    }

    /**
     * <p>
     * Holds pre-built lookup structures to avoid repeated computation during row processing.
     * </p>
     *
     * @param reportFieldByIdMap      map of report field id → ReportField (for GET action)
     * @param reportFieldByOrderMap   map of computed axis order → ReportField (for APPLY action)
     * @param columnNameDetails       map of column name → report field id (for APPLY action)
     * @param configuredColumnDetails map of column name → column detail pair (for configured columns)
     */
    private record RowProcessingContext(Map<Long, ReportField> reportFieldByIdMap, Map<Long, ReportField> reportFieldByOrderMap,
            Map<Long, ReportField> reportFieldByColumnIdMap, Map<String, Long> columnNameDetails,
            Map<String, Pair<String, Long>> configuredColumnDetails) {
    }

    /**
     * <p>
     * Pre-builds lookup maps from the view's report fields to avoid repeated {@code stream().filter().findFirst()}
     * during per-row processing. This is the key performance optimization — converting O(N×M) stream scans
     * into O(1) map lookups.
     * </p>
     *
     * @param view                 the view containing report fields
     * @param isApplyConfiguration whether the request is an apply configuration
     * @param request              the original request
     * @return the pre-built processing context
     */
    private RowProcessingContext buildRowProcessingContext(final V view,
                                                           final boolean isApplyConfiguration,
                                                           final Request request) {
        final Collection<ReportField> reportFields = view.getReportFields();
        final Map<Long, ReportField> reportFieldByIdMap = new HashMap<>(reportFields.size());
        final Map<Long, ReportField> reportFieldByOrderMap = new HashMap<>(reportFields.size());
        final Map<Long, ReportField> reportFieldByColumnIdMap = new HashMap<>(reportFields.size());

        for (final ReportField reportField : reportFields) {
            reportFieldByIdMap.put(reportField.id(), reportField);
            reportFieldByColumnIdMap.put(reportField.getColumnId(), reportField);

            if (isApplyConfiguration) {
                reportFieldByOrderMap.put(reportField.getAxisType() + (Axis.X_AXIS == reportField.getAxis() ? reportField.getOrder()
                        : NumericalConstant.THREE), reportField);
            }
        }

        return new RowProcessingContext(reportFieldByIdMap, reportFieldByOrderMap, reportFieldByColumnIdMap,
                request.getColumnNameDetails(), request.getConfiguredColumnDetails());
    }

    /**
     * <p>
     * Processes all data rows from the analytics query, constructing graph axes for each column value.
     * Uses pre-built lookup maps from {@link RowProcessingContext} for O(1) report field resolution.
     * </p>
     *
     * @param orgId                the organisation id
     * @param with                 the WITH clause context
     * @param isApplyConfiguration whether this is an apply action
     * @param operationType        the operation type
     * @param totalRecords         the total record count
     * @param analyticsLimit       the analytics limit (start/limit)
     * @param context              the pre-built row processing context
     * @param xAxisList            accumulator for x-axis graph axes
     * @param yAxisList            accumulator for y-axis graph axes
     * @param underlyingDataList   accumulator for underlying data graph axes
     */
    private void processDataRows(final Long orgId,
                                 final With with,
                                 final boolean isApplyConfiguration,
                                 final OperationType operationType,
                                 final Long totalRecords,
                                 final AnalyticsLimit analyticsLimit,
                                 final RowProcessingContext context,
                                 final List<GraphAxis<Object>> xAxisList,
                                 final List<GraphAxis<Object>> yAxisList,
                                 final List<GraphAxis<Object>> underlyingDataList) {
        final Map<Long, GraphAxis<Object>> reportFieldMap = new HashMap<>();
        final AtomicLong rowIdx = new AtomicLong(NumericalConstant.ONE);
        final long startTime = System.currentTimeMillis();

        analyticsDataFetcher.fetchData(orgId, with, row ->
        {
            row.forEach((columnName, value) ->
            {
                if (isApplyConfiguration) {
                    processApplyColumn(columnName, value, context, reportFieldMap, rowIdx, operationType, totalRecords,
                            analyticsLimit, xAxisList, yAxisList);
                } else {
                    processGetColumn(columnName, value, context, reportFieldMap, rowIdx, operationType, totalRecords,
                            analyticsLimit, xAxisList, yAxisList, underlyingDataList);
                }
            });

            rowIdx.incrementAndGet();
        });

        LOGGER.debug("Analytics: Data processing completed in {} milliseconds, orgId [{}]", System.currentTimeMillis() - startTime, orgId);
    }

    /**
     * <p>
     * Processes a single column value for the APPLY configuration action. Uses the pre-built
     * {@code reportFieldByOrderMap} for O(1) report field lookup instead of streaming.
     * </p>
     *
     * @param columnName     the column name from the result row
     * @param value          the column value
     * @param context        the pre-built row processing context
     * @param reportFieldMap map of report field id → already-created graph axis
     * @param rowIdx         the current row index
     * @param operationType  the operation type
     * @param totalRecords   the total record count
     * @param analyticsLimit the analytics limit
     * @param xAxisList      accumulator for x-axis graph axes
     * @param yAxisList      accumulator for y-axis graph axes
     */
    private void processApplyColumn(final String columnName,
                                    final Object value,
                                    final RowProcessingContext context,
                                    final Map<Long, GraphAxis<Object>> reportFieldMap,
                                    final AtomicLong rowIdx,
                                    final OperationType operationType,
                                    final Long totalRecords,
                                    final AnalyticsLimit analyticsLimit,
                                    final List<GraphAxis<Object>> xAxisList,
                                    final List<GraphAxis<Object>> yAxisList) {
        final Long reportFieldId = context.columnNameDetails().get(columnName);

        if (reportFieldId == null) {
            return;
        }

        final GraphAxis<Object> graphAxis = reportFieldMap.computeIfAbsent(reportFieldId, id ->
        {
            final ReportField reportField = context.reportFieldByOrderMap().get(reportFieldId);

            if (reportField == null) {
                return null;
            }

            return createAndRegisterGraphAxis(reportField, rowIdx.get(), value, operationType,
                    totalRecords, analyticsLimit, xAxisList, yAxisList);
        });

        if (graphAxis != null) {
            graphAxis.getAxisValues().add(AxisValue.create(value));
            LOGGER.debug("Analytics: Value added to graph axis for view column id: {}", reportFieldId);
        }
    }

    /**
     * <p>
     * Processes a single column value for the GET action. Handles both report-field columns
     * (suffix pattern {@code _<id>}) and configured columns. Uses pre-built
     * {@code reportFieldByIdMap} for O(1) lookup.
     * </p>
     *
     * @param columnName         the column name from the result row
     * @param value              the column value
     * @param context            the pre-built row processing context
     * @param reportFieldMap     map of report field id → already-created graph axis
     * @param rowIdx             the current row index
     * @param operationType      the operation type
     * @param totalRecords       the total record count
     * @param analyticsLimit     the analytics limit
     * @param xAxisList          accumulator for x-axis graph axes
     * @param yAxisList          accumulator for y-axis graph axes
     * @param underlyingDataList accumulator for underlying data graph axes
     */
    private void processGetColumn(final String columnName,
                                  final Object value,
                                  final RowProcessingContext context,
                                  final Map<Long, GraphAxis<Object>> reportFieldMap,
                                  final AtomicLong rowIdx,
                                  final OperationType operationType,
                                  final Long totalRecords,
                                  final AnalyticsLimit analyticsLimit,
                                  final List<GraphAxis<Object>> xAxisList,
                                  final List<GraphAxis<Object>> yAxisList,
                                  final List<GraphAxis<Object>> underlyingDataList) {
        if (COLUMN_SUFFIX_PATTERN.matcher(columnName).matches()) {
            final Long reportFieldId = Long.parseLong(columnName.substring(columnName.lastIndexOf('_') + NumericalConstant.ONE));

            LOGGER.debug("Analytics: Processing row for view column id: {}", reportFieldId);

            final GraphAxis<Object> graphAxis = reportFieldMap.computeIfAbsent(reportFieldId, id ->
            {
                final ReportField reportField = context.reportFieldByIdMap().get(reportFieldId);

                if (reportField == null) {
                    return null;
                }

                return createAndRegisterGraphAxis(reportField, rowIdx.get(), value, operationType,
                        totalRecords, analyticsLimit, xAxisList, yAxisList);
            });

            if (graphAxis != null) {
                graphAxis.getAxisValues().add(AxisValue.create(value));
                LOGGER.debug("Analytics: Value added to graph axis with view column ID: {}", reportFieldId);
            }
        } else {
            processConfiguredColumn(columnName, value, context, totalRecords, analyticsLimit, underlyingDataList);
        }
    }

    /**
     * <p>
     * Processes a configured column (non-standard column name, not matching the suffix pattern).
     * Creates underlying data graph axes for columns present in the configured column details map.
     * </p>
     *
     * @param columnName         the column name from the result row
     * @param value              the column value
     * @param context            the pre-built row processing context
     * @param totalRecords       the total record count
     * @param analyticsLimit     the analytics limit
     * @param underlyingDataList accumulator for underlying data graph axes
     */
    private void processConfiguredColumn(final String columnName,
                                         final Object value,
                                         final RowProcessingContext context,
                                         final Long totalRecords,
                                         final AnalyticsLimit analyticsLimit,
                                         final List<GraphAxis<Object>> underlyingDataList) {
        final Pair<String, Long> column = context.configuredColumnDetails().get(columnName);

        if (column == null) {
            return;
        }

        final String columnValue = column.getKey();
        final GraphAxis<Object> newGraphAxis = new GraphAxis<>(columnValue, value);
        final Long columnId = column.getValue();

        if (columnId != null) {
            final ReportField reportField = context.reportFieldByColumnIdMap().get(columnId);

            if (reportField != null) {
                final Long anaColumnId = reportField.getColumnId();

                newGraphAxis.getColumnToFieldIdMap().put(anaColumnId, reportField.getFieldId());
                newGraphAxis.getColumnMap().put(anaColumnId, value);
                newGraphAxis.getColumnNameMap().put(columnValue, anaColumnId);
            }
        }

        newGraphAxis.setTotalRecords(totalRecords);
        newGraphAxis.setAnalyticsLimit(analyticsLimit);
        underlyingDataList.add(newGraphAxis);
    }

    /**
     * <p>
     * Creates a new {@link GraphAxis}, sets its common properties, registers it in the appropriate
     * axis list (x or y), and returns it. This eliminates the duplicate graph axis creation code
     * that was previously present in both the APPLY and GET branches.
     * </p>
     *
     * @param reportField    the report field backing this axis
     * @param rowIdx         the current row index
     * @param value          the first column value (stored in columnMap)
     * @param operationType  the operation type
     * @param totalRecords   the total record count
     * @param analyticsLimit the analytics limit
     * @param xAxisList      accumulator for x-axis graph axes
     * @param yAxisList      accumulator for y-axis graph axes
     * @return the newly created graph axis
     */
    private GraphAxis<Object> createAndRegisterGraphAxis(final ReportField reportField,
                                                         final long rowIdx,
                                                         final Object value,
                                                         final OperationType operationType,
                                                         final Long totalRecords,
                                                         final AnalyticsLimit analyticsLimit,
                                                         final List<GraphAxis<Object>> xAxisList,
                                                         final List<GraphAxis<Object>> yAxisList) {
        final GraphAxis<Object> graphAxis = GraphAxis.create(rowIdx, reportField);

        graphAxis.setOperationType(operationType);
        graphAxis.getColumnMap().put(reportField.getColumnId(), value);
        graphAxis.setTotalRecords(totalRecords);
        graphAxis.setAnalyticsLimit(analyticsLimit);

        if (Axis.X_AXIS == reportField.getAxis()) {
            xAxisList.add(graphAxis);
        } else {
            yAxisList.add(graphAxis);
        }

        LOGGER.debug("Analytics: New graph axis created for report field: {}", reportField.id());

        return graphAxis;
    }

    /**
     * Retrieves the total records based on the given select query and request parameters.
     *
     * @param orgId       The organization ID for which the data is being fetched.
     * @param selectQuery The query containing selection criteria and constraints.
     * @return count of total records
     */
    private Long getTotalRecords(final Long orgId, final SelectQuery selectQuery) {
        final Table baseTable = selectQuery.getBaseTable();
        final CountQuery countQuery = CountQuery.get(baseTable, baseTable.getPKColumn());

        countQuery.setWhereClause(selectQuery.getWhereClause());
        countQuery.addJoinClause(selectQuery.getJoinClause());

        return DataStoreProvider.getSecureOrgDataStore(orgId, DatabaseType.OLAP).get(countQuery);
    }

    /**
     * <p>
     * Abstract method to generate a response based on the list of graph axes.
     * </p>
     *
     * @param graphAxisList The list of graph axes to be included in the response.
     * @return The generated response object.
     */
    protected abstract Response getResponse(final @NonNull List<GraphAxis<Object>> graphAxisList);

    /**
     * <p>
     * Abstract method to obtain the select query converter.
     * </p>
     *
     * @return The select query converter instance.
     */
    protected abstract SelectQueryConverter<V, Request> getSelectQueryConverter();

    /**
     * <p>
     * Generates default (empty) x-axis and y-axis entries when no data is found.
     * Y-axis entries are populated with a default value of 0.
     * </p>
     *
     * @param totalRecords   total records for the chart
     * @param xAxisList      The list of x-axis graph axes
     * @param yAxisList      The list of y-axis graph axes
     * @param view           Contains chartView object for the Chart
     * @param operationType  the operation type to set
     * @param analyticsLimit Holds the LimitClause details
     */
    private void generateNoDataResponse(final Long totalRecords,
                                        final List<GraphAxis<Object>> xAxisList,
                                        final List<GraphAxis<Object>> yAxisList,
                                        final V view,
                                        final OperationType operationType,
                                        final AnalyticsLimit analyticsLimit) {
        final AtomicLong rowIdx = new AtomicLong(NumericalConstant.ONE);
        final Collection<ReportField> reportFields = view.getReportFields();

        for (final ReportField reportField : reportFields) {
            final GraphAxis<Object> graphAxis = GraphAxis.create(rowIdx.get(), reportField);

            graphAxis.setOperationType(operationType);
            graphAxis.setTotalRecords(totalRecords);
            graphAxis.setAnalyticsLimit(analyticsLimit);

            if (Axis.X_AXIS == reportField.getAxis()) {
                xAxisList.add(graphAxis);
            } else {
                graphAxis.getColumnMap().put(reportField.getColumnId(), NumericalConstant.ZERO);
                graphAxis.getAxisValues().add(AxisValue.<Object>create(NumericalConstant.ZERO));
                yAxisList.add(graphAxis);
            }

            LOGGER.debug("Analytics: Default graph axis created with value 0 for view column id: {}", reportField.getColumnId());
        }
    }
}
