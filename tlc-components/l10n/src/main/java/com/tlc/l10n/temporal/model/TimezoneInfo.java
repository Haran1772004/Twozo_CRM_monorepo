    private static final Map<String, TimezoneInfo> TIMEZONE_BY_COUNTRY = new HashMap<>();
    private static final Map<Integer, TimezoneInfo> TIMEZONE_BY_ID = new HashMap<>();
    private final TimeZone timeZone;
    private final int id;
    private final String displayName;

    static {

        for (final TimezoneInfo timezoneInfo : TimezoneInfo.values()) {
            TIMEZONE_BY_COUNTRY.put(timezoneInfo.getTimeZone().getID().toLowerCase(), timezoneInfo);
            TIMEZONE_BY_ID.put(timezoneInfo.id, timezoneInfo);
        }
    }

    TimezoneInfo(final TimeZone timeZone, final String displayName, final int id) {
        this.timeZone = timeZone;
        this.displayName = displayName;
        this.id = id;
    }

    /**
     * <p>
     * Gets the {@link TimeZone}
     * </p>
     *
     * @return {@link TimeZone}
     */
    public TimeZone getTimeZone() {
        return timeZone;
    }

    /**
     * <p>
     * Gets the id from timezone
     * </p>
     *
     * @return id
     */
    public int getId() {
        return id;
    }

    /**
     * <p>
     * Gets the display name from timezone
     * </p>
     *
     * @return The timezone display name
     */
    public String getDisplayName() {
        return displayName;
    }

    /**
     * <p>
     * Gets the {@link TimezoneInfo} by country
     * </p>
     *
     * @param country Represents the country name
     * @return {@link TimezoneInfo}
     */
    public static TimezoneInfo getTimezoneByCountry(final String country) {
        final TimezoneInfo timezoneInfo = TIMEZONE_BY_COUNTRY.get(country.toLowerCase());

        if (Objects.nonNull(timezoneInfo)) {
            return timezoneInfo;
        }
        throw ErrorCode.get(L10NErrorCode.INVALID_TIMEZONE);
    }

    /**
     * <p>
     * Gets the {@link TimezoneInfo} by id
     * </p>
     *
     * @param id Represents the timezone id
     * @return {@link TimezoneInfo}
     */
    public static TimezoneInfo getTimezoneById(final int id) {
        final TimezoneInfo timezoneInfo = TIMEZONE_BY_ID.get(id);

        if (Objects.nonNull(timezoneInfo)) {
            return timezoneInfo;
        }
        throw ErrorCode.get(L10NErrorCode.INVALID_TIMEZONE);
    }
